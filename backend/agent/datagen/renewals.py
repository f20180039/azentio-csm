"""Synthetic policy book for the renewal desk. Everything is fictional; same seed, same SQL."""
import argparse
import json
import random
import sys
from datetime import date, timedelta
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from datagen.common import FIRST, LAST

INSURER = "Lotusleaf General Insurance"
PRODUCTS = {
    "Health family floater": "HF",
    "Health individual": "HI",
    "Motor comprehensive": "MC",
    "Motor third-party": "MT",
    "Term life": "TL",
}
OPD = {"code": "OPD", "name": "Outpatient cover", "premium": 2100, "optional": True}
MEDICAL_INFLATION = "Medical inflation"
COLUMNS = ["id", "holder_name", "date_of_birth", "mobile_last4", "product", "sum_insured", "expires_on",
           "last_premium", "renewal_premium", "premium_breakdown", "addons", "claim_rejected_12m",
           "open_complaint", "autodebit_failed", "reminders_ignored", "do_not_call"]


def _row(id, name, dob, last4, product, sum_insured, expires_on, last, breakdown, addons=None, **flags):
    return {
        "id": id, "holder_name": name, "date_of_birth": dob, "mobile_last4": last4, "product": product,
        "sum_insured": sum_insured, "expires_on": expires_on, "last_premium": last,
        "renewal_premium": last + sum(b["amount"] for b in breakdown), "premium_breakdown": breakdown,
        "addons": addons or [], "claim_rejected_12m": False, "open_complaint": False,
        "autodebit_failed": False, "reminders_ignored": 0, "do_not_call": False, **flags,
    }


def _fixed(today: date) -> list[dict]:
    d = lambda n: today + timedelta(days=n)  # noqa: E731
    return [
        _row("HF-2291-0457", "Meera Iyer", date(1980, 3, 14), "4821", "Health family floater", 1000000, d(5),
             15120, [{"label": "Age band 41–45 to 46–50", "amount": 2610},
                     {"label": MEDICAL_INFLATION, "amount": 720}], [OPD], reminders_ignored=2),
        _row("MC-3380-1126", "Arjun Mehta", date(1988, 7, 22), "9034", "Motor comprehensive", 650000, d(9),
             11800, [{"label": "No-claim bonus lapsed", "amount": 1180}],
             open_complaint=True, claim_rejected_12m=True, reminders_ignored=1),
        _row("MT-1045-7782", "Sana Qureshi", date(1993, 1, 9), "2276", "Motor third-party", 0, d(3),
             2094, [], reminders_ignored=0),
        _row("TL-5512-0309", "Kavya Rao", date(1985, 11, 30), "7719", "Term life", 10000000, d(12),
             21400, [{"label": "Age band 36–40 to 41–45", "amount": 1900}],
             autodebit_failed=True, reminders_ignored=2),
        _row("HI-7710-6643", "Rohan Das", date(1991, 5, 17), "6150", "Health individual", 500000, d(21),
             11000, [{"label": MEDICAL_INFLATION, "amount": 990}], reminders_ignored=0),
    ]


def _random_row(r: random.Random, i: int, today: date, taken: set[str]) -> dict:
    product = r.choice(list(PRODUCTS))
    while True:
        pid = f"{PRODUCTS[product]}-{r.randint(1000, 9999)}-{r.randint(1000, 9999)}"
        if pid not in taken:
            taken.add(pid)
            break
    name = f"{r.choice(FIRST)} {r.choice(LAST)}"
    dob = date(r.randint(1960, 2000), r.randint(1, 12), r.randint(1, 28))
    health, motor = product.startswith("Health"), product.startswith("Motor")
    last = r.randrange(2000, 30000, 10) if product != "Motor third-party" else r.randrange(2000, 4000, 10)
    pct = r.uniform(0.16, 0.30) if i < 8 else r.uniform(0.0, 0.12)
    total = round(last * pct)
    reason = MEDICAL_INFLATION if health else "No-claim bonus lapsed" if motor else "Age band step-up"
    first = total // 2
    breakdown = [{"label": reason, "amount": first}, {"label": "Taxes and levies", "amount": total - first}] \
        if total else []
    expires = today + timedelta(days=r.randint(1, 7) if i < 6 else r.randint(8, 60))
    return _row(pid, name, dob, f"{r.randint(0, 9999):04d}", product, r.choice([0, 300000, 500000, 1000000]),
                expires, last, breakdown, [OPD] if health and r.random() < 0.4 else [],
                open_complaint=i % 11 == 0, do_not_call=i % 13 == 5, claim_rejected_12m=r.random() < 0.1,
                autodebit_failed=r.random() < 0.12, reminders_ignored=r.choice([0, 0, 1, 2, 3]))


def build_policies(seed: int, count: int, today: date) -> list[dict]:
    rows = _fixed(today)
    r = random.Random(seed)
    taken = {x["id"] for x in rows}
    rows += [_random_row(r, i, today, taken) for i in range(count - len(rows))]
    return rows


def _lit(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, (list, dict)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def render_sql(rows: list[dict]) -> str:
    out = [f"-- Synthetic renewal book for {INSURER}. Generated by agent/datagen/renewals.py; do not edit."]
    updates = ", ".join(f"{c} = EXCLUDED.{c}" for c in COLUMNS[1:])
    for row in rows:
        values = ", ".join(_lit(row[c]) for c in COLUMNS)
        out.append(f"INSERT INTO policies ({', '.join(COLUMNS)}) VALUES ({values}) "
                   f"ON CONFLICT (id) DO UPDATE SET {updates};")
    return "\n".join(out) + "\n"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--count", type=int, default=40)
    p.add_argument("--today", type=date.fromisoformat, default=date.today())
    p.add_argument("--out", type=Path, required=True)
    a = p.parse_args()
    a.out.write_text(render_sql(build_policies(a.seed, a.count, a.today)), encoding="utf-8")


if __name__ == "__main__":
    main()
